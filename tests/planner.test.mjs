import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {groupedUnits,setQuantity,inputConfidence,supplyRequest,normalizeView} from '../web/planner.mjs';
import {calculate} from '../web/calc.mjs';
import {setLanguage,configureTranslations} from '../web/i18n.mjs';
const cat=JSON.parse(readFileSync(new URL('../app/seed.json',import.meta.url)));
const original=JSON.parse(readFileSync(new URL('../app/example.json',import.meta.url)));
const p=structuredClone(original),id=p.units[0].equipment_id;
assert.equal(normalizeView(null),'basic');assert.equal(normalizeView('bad'),'basic');assert.equal(normalizeView('advanced'),'advanced');
assert.equal(groupedUnits(p).find(g=>g.id===id).quantity,2);
const phases=p.units.map(u=>u.phase);
setQuantity(p,cat,id,2);
assert.deepEqual(p.units.map(u=>u.phase),phases,'Switching/retaining quantities must preserve phase assignments');
setQuantity(p,cat,id,4);
assert.equal(groupedUnits(p).find(g=>g.id===id).quantity,4);
assert.deepEqual(p.units.slice(0,original.units.length),original.units);
assert.equal(p.generator_kva,original.generator_kva);
const before=structuredClone(p);
for(const value of [-1,1.5,301,NaN])assert.throws(()=>setQuantity(p,cat,id,value));
assert.deepEqual(p,before,'Invalid quantities must not partially mutate the project');
assert.throws(()=>setQuantity(p,cat,'missing',1));
setQuantity(p,cat,id,1);
assert.equal(p.units.filter(u=>u.equipment_id===id).length,1);
assert.equal(p.units.find(u=>u.equipment_id===id).phase,original.units[0].phase);
p.units.push({equipment_id:'missing',phase:'L1'});
assert.equal(inputConfidence(p,cat).missing,1);
setQuantity(p,cat,'missing',0);
assert.equal(inputConfidence(p,cat).missing,0);
setLanguage('en');
assert.throws(()=>supplyRequest({...original,units:[]},cat));
assert.throws(()=>supplyRequest({...original,units:[{equipment_id:'missing',phase:'L1'}]},cat));
const gen=supplyRequest(original,cat);
assert.match(gen,/at least 40 kVA prime/);
assert.doesNotMatch(gen,/Battery requirement/);
assert(gen.includes('\nEquipment:\n'));
const b={...original,power_mode:'battery'};
const battery=supplyRequest(b,cat);
assert.match(battery,/Battery requirement/);
assert.doesNotMatch(battery,/Generator request|Fuel allowance|Fuel quantity/);
const br=calculate({...b,vehicle:{generator_weight_kg:1200,battery_weight_kg:2200,other_weight_kg:300}},cat);
assert.equal(br.knownSourceWeight,2500);
assert.equal(br.fuelLitres,null);
assert.equal(calculate({...b,generator_pf:0.5},cat).requiredVA,calculate({...b,generator_pf:1},cat).requiredVA,'Battery-only sizing must not depend on generator settings');
const fixed=supplyRequest({...original,setup_mode:'fixed',venue_supply:{L1:16,L2:16,L3:16}},cat);
assert.match(fixed,/Venue supply is insufficient/);
assert.match(fixed,/Generator fallback: 40/);
const fixedBattery=supplyRequest({...b,setup_mode:'fixed'},cat);
assert.match(fixedBattery,/Battery fallback:/);
assert.doesNotMatch(fixedBattery,/Generator fallback:/);
const fuel=supplyRequest({...original,generator_fuel_curve:{p25:2,p50:4,p75:6,p100:8},program_multiplier:2},cat);
assert.match(fuel,/from the supplier curve/);
configureTranslations(JSON.parse(readFileSync(new URL('../web/nl.json',import.meta.url))));setLanguage('nl');
const nl=supplyRequest({...original,name:'other'},cat);
assert.match(nl,/Aanvraag stroomvoorziening/);assert.match(nl,/Project: other/);
assert.match(nl,/Aggregaataanvraag: minimaal 40 kVA/);
assert.match(nl,/2 × 30-inch M-Force infra/);
assert.match(nl,/Invoerkwaliteit:/);
console.log('Basic/advanced defaults, grouped quantities, phase preservation, evidence and supply requests passed');
