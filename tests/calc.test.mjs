import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {calculate} from '../web/calc.mjs';
const cat=JSON.parse(readFileSync(new URL('../app/seed.json',import.meta.url),'utf8'));
const project=JSON.parse(readFileSync(new URL('../app/example.json',import.meta.url),'utf8'));
const r=calculate(project,cat);
assert.equal(r.referenceVA,5660);
assert.equal(r.designVA,23580);
assert.equal(r.suggestedKVA,40);
assert.equal(r.generatorOK,true);
assert(Math.abs(r.phases.L1.design_va-8790)<0.01);
assert.equal(r.phases.L2.design_va,6790);
assert.equal(r.phases.L3.design_va,8000);
assert.equal(r.unknownWeights,6);
assert.equal(r.batteryNominalKWh,null);
const battery=calculate({...project,power_mode:'battery'},cat);
assert(battery.batteryNominalKWh>55&&battery.batteryNominalKWh<60);
const small={...project,generator_kva:20};
assert.equal(calculate(small,cat).generatorOK,false);
const unbalanced={...project, units:project.units.map(u=>({...u,phase:'L1'}))};
assert(calculate(unbalanced,cat).suggestedKVA>40);
console.log('Calculator test passed: reference, design, phases, batteries, undersizing and imbalance');

const storage={...project,power_mode:'hybrid',battery_installed_kwh:120,inverter_kva:40,fuel_rate_lph:5.5,vehicle:{...project.vehicle,generator_weight_kg:1200,battery_weight_kg:2200,other_weight_kg:300,payload_kg:5000}};
const sr=calculate(storage,cat);
assert.equal(sr.inverterCapacityOK,true);
assert(sr.batteryRuntimeH>8);
assert.equal(sr.fuelLitres,44);
assert.equal(sr.totalKnownWeight,3700);
assert.equal(sr.unknownSourceWeights,0);
assert.equal(sr.payloadRemaining,1300);
assert.equal(sr.unknownWeights,6);
const tooSmall=calculate({...storage,inverter_kva:15,battery_installed_kwh:20},cat);
assert.equal(tooSmall.inverterCapacityOK,false);
assert(tooSmall.batteryRuntimeH<8);
console.log('V1.1 source, storage and vehicle screening passed');

const generator=calculate({...storage,power_mode:'generator'},cat);
assert.equal(generator.usesBattery,false);
assert.equal(generator.batteryInstalled,0);
assert.equal(generator.inverterKVA,0);
assert.equal(generator.batteryRuntimeH,null);
assert.equal(generator.inverterCapacityOK,false);
assert.equal(generator.totalKnownWeight,1500);
assert.equal(generator.payloadRemaining,3500);
assert.equal(generator.unknownSourceWeights,0);
assert.equal(generator.suggestedKVA,sr.suggestedKVA);
assert.equal(storage.battery_installed_kwh,120,'Switching modes must preserve saved settings');
assert.equal(calculate({...storage,power_mode:'battery'},cat).batteryInstalled,120);
assert.equal(calculate({...storage,power_mode:'hybrid'},cat).totalKnownWeight,3700);
const missingBatteryWeight={...storage,power_mode:'generator',vehicle:{...storage.vehicle,battery_weight_kg:null}};
assert.equal(calculate(missingBatteryWeight,cat).unknownSourceWeights,0);
console.log('Generator-only mode excludes battery values and weight; battery/hybrid retain them');
