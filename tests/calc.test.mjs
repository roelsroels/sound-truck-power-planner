import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {calculate} from '../web/calc.mjs';
const cat=JSON.parse(readFileSync(new URL('../app/seed.json',import.meta.url),'utf8'));
const project=JSON.parse(readFileSync(new URL('../app/example.json',import.meta.url),'utf8'));
const r=calculate(project,cat);
assert.equal(r.referenceVA,5660);
assert.equal(r.designVA,23580);
assert.equal(r.suggestedKVA,40);
assert.equal(r.generatorOK,true);
assert(Math.abs(r.phases.L1.design_va-8790)<0.01);
assert.equal(r.phases.L2.design_va,6790);
assert.equal(r.phases.L3.design_va,8000);
assert.equal(r.unknownWeights,6);
assert(r.batteryNominalKWh>55&&r.batteryNominalKWh<60);
const small={...project,generator_kva:20};
assert.equal(calculate(small,cat).generatorOK,false);
const unbalanced={...project, units:project.units.map(u=>({...u,phase:'L1'}))};
assert(calculate(unbalanced,cat).suggestedKVA>40);
console.log('Calculator test passed: reference, design, phases, batteries, undersizing and imbalance');
