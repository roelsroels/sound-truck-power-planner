import assert from 'node:assert/strict';
import {calculate} from '../web/calc.mjs';
import {venueSupply,supplySummary} from '../web/supply.mjs';
const cat=[{id:'load',design_va:2300,reference_va:1000,power_factor:1}];
const p={setup_mode:'fixed',units:[{equipment_id:'load',phase:'L1'}],voltage_v:230,headroom_pct:25,generator_kva:10};
const calc=calculate(p,cat);
const assessment=venueSupply(p,calc);
assert.equal(assessment.requiredA.L1,12.5);
assert.equal(assessment.requiredKW,2.875);
assert.equal(assessment.requiredKVA,2.875);
assert.equal(assessment.status,'unknown');
p.venue_supply={L1:12.5,L2:0,L3:0};
assert.equal(venueSupply(p,calc).status,'covered');
p.venue_supply={L1:12,L2:100,L3:100};
assert.equal(venueSupply(p,calc).status,'insufficient');
p.venue_supply={L1:0};
assert.equal(venueSupply(p,calc).status,'insufficient');
p.venue_supply={L1:20,L2:'',L3:0};
assert.equal(venueSupply(p,calc).status,'unknown');
assert.match(supplySummary(p,calc).join('\n'),/Generator fallback: 10 kVA/);
assert.deepEqual(supplySummary({...p,setup_mode:undefined},calc),['Setup: Mobile']);
const switched=JSON.parse(JSON.stringify({...p,setup_mode:'mobile'}));
switched.setup_mode='fixed';
assert.deepEqual(switched.venue_supply,p.venue_supply);
assert.deepEqual(venueSupply({...p,generator_pf:0.5},calculate({...p,generator_pf:0.5},cat)),venueSupply(p,calc));
assert.equal(venueSupply({...p,voltage_v:115},calculate({...p,voltage_v:115},cat)).requiredA.L1,25);
console.log('Venue per-phase requirements, shortfalls, unknown supply and mode compatibility passed');
